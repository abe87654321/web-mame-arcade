/**
 * Object storage for closed input logs (docs/contracts/input-log.md, T30).
 * T30 ships a local-disk backend (docs/06: "local disk or MinIO"); a
 * MinIO/S3 backend is a drop-in later (T42). The interface takes fully-encoded
 * bytes so callers own the gzip/JSON encoding.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve, sep } from "node:path";

export interface LogStore {
  /** Write `bytes` under `key`; resolves when durable enough for the caller. */
  put(key: string, bytes: Uint8Array): Promise<void>;
}

/** In-memory store for tests; also exposes reads and the key list. */
export interface MemoryLogStore extends LogStore {
  get(key: string): Uint8Array | undefined;
  keys(): string[];
}

export function createMemoryLogStore(): MemoryLogStore {
  const objects = new Map<string, Uint8Array>();
  return {
    put: async (key, bytes) => {
      objects.set(key, bytes);
    },
    get: (key) => objects.get(key),
    keys: () => [...objects.keys()],
  };
}

/**
 * Write logs under `dir`. Keys are generated by the relay and never
 * user-supplied, but the resolved path is still constrained to `dir` so a
 * future caller cannot escape it.
 */
export function createLocalDiskLogStore({ dir }: { dir: string }): LogStore {
  const root = resolve(dir);
  return {
    put: async (key, bytes) => {
      const target = resolve(root, key);
      if (target !== root && !target.startsWith(root + sep)) {
        throw new Error(`log key escapes the log directory: ${key}`);
      }
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, bytes);
    },
  };
}

/** Read a log back from a local-disk store (verifier/tests, T33). */
export async function readLocalLog(dir: string, key: string): Promise<Uint8Array> {
  return new Uint8Array(await readFile(resolve(dir, key)));
}
